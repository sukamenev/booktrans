# ------------------------------------------------------ правка из tune.conf

LINE = re.compile(r"^\s*([A-Z_]{2,})\s*=\s*([-\d.,\s()]+?)\s*(?:#.*)?$")


def _value(s):
    """«80», «0.65», «(60, 180, 300)» → число или набор чисел."""
    nums = re.findall(r"-?\d+(?:\.\d+)?", s)
    if not nums:
        return None
    vals = [float(x) if "." in x else int(x) for x in nums]
    return tuple(vals) if s.strip().startswith("(") or len(vals) > 1 else vals[0]


def config_dir():
    """Папка настроек пользователя — своя на каждой системе.

    Стандартной библиотеке такое неизвестно; ради этих пяти строк существует
    пакет `platformdirs`, но тянуть зависимость в проект с одной-единственной
    незачем. На Linux спрашиваем `XDG_CONFIG_HOME` (обычно она не задана, и
    соглашение предписывает `~/.config`), на прочих системах — их места.
    """
    if os.name == "nt":
        base = os.environ.get("APPDATA") or os.path.expanduser("~/AppData/Roaming")
    elif sys.platform == "darwin":
        base = os.path.expanduser("~/Library/Application Support")
    else:
        base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return os.path.join(base, "booktrans")


def path():
    """Где искать пользовательские настройки — рядом с промптами и профилями."""
    return os.path.join(config_dir(), "tune.conf")


def load(where=None):
    """Наложить `tune.conf`. Возвращает {имя: (было, стало)}.

    Имя не отсюда — молча мимо: опечатка в названии не должна менять поведение
    конвейера втихую, но и валить прогон из-за строки в настройках незачем.
    Зовётся при первом обращении к модулю, до того как остальные разберут
    отсюда имена, — иначе правка не дошла бы ни до кого.
    """
    changed = {}
    try:
        text = open(where or path(), encoding="utf-8").read()
    except OSError:
        return changed
    for line in text.splitlines():
        m = LINE.match(line)
        if not m or m.group(1) not in globals():
            continue
        val = _value(m.group(2))
        if val is None or globals()[m.group(1)] == val:
            continue
        changed[m.group(1)] = (globals()[m.group(1)], val)
        globals()[m.group(1)] = val
    return changed


CHANGED = load()
