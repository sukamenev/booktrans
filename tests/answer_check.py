#!/usr/bin/env python3
"""Проверка разбора ответа модели: блоки и замечания редактора.

Блоки разбираются строго — недостача или лишний идентификатор роняют кусок, и
это правильно: молча склеенный перевод хуже повторного захода. А вот хвост
после метки замечаний берётся как есть, и в него попадает всё, чем модель
закончила ответ: своя оградка, закрывающая скобка к нашей же метке, тег
внутренней разметки. В файле замечаний такой мусор стоял в каждом четвёртом
куске.

    python3 tests/answer_check.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from booktrans import pipeline as P                      # noqa: E402

# (что пришло в хвосте, что должно остаться)
TAILS = [
    ("замечание про термин", "замечание про термин"),
    ("замечание\n</invoke>", "замечание"),
    ("замечание\n</NOTES>", "замечание"),
    ("замечание\n</<<NOTES>>>", "замечание"),
    ("замечание\n</thinking>", "замечание"),
    ("замечание\n```", "замечание"),
    ("замечание\n```\n</invoke>", "замечание"),
    ("первая строка\nвторая строка\n</details>", "первая строка\nвторая строка"),
    # Ярлык ссылки в конце замечания — не леса: редактор цитирует им текст.
    ("s01.b0003: см. <a1>тут</a1>", "s01.b0003: см. <a1>тут</a1>"),
    # Пусто и есть пусто: «замечаний нет» отсекается дальше, по длине.
    ("</invoke>", ""),
]


def main():
    bad = 0

    def ok(name, cond, got=""):
        nonlocal bad
        print(f"  {name:46} {'совпадает' if cond else 'РАСХОЖДЕНИЕ'}"
              + ("" if cond else f"   вышло: {got!r}"))
        bad += not cond

    for src, want in TAILS:
        got = P._unscaffold(src)
        ok(f"хвост {src.splitlines()[-1][:26]!r}", got == want, got)

    # Разбор целиком: леса снимаются только с хвоста, текст блоков цел.
    out = ("<<<P s01.b0001>>>\nПервый абзац.\n"
           "<<<P s01.b0002>>>\nВторой абзац.\n"
           "<<<NOTES>>>\ns01.b0002: сомнительный термин.\n</invoke>")
    got, tail = P.parse_blocks(out, expected=["s01.b0001", "s01.b0002"],
                               extra_tag="NOTES")
    ok("блоки разобраны", got == {"s01.b0001": "Первый абзац.",
                                  "s01.b0002": "Второй абзац."}, got)
    ok("замечание без лесов", tail == "s01.b0002: сомнительный термин.", tail)

    # Один перевод на два блока. Разбору это не видно: идентификаторы на
    # месте, пустых нет, — а один абзац книги остаётся непереведённым.
    def answer(*pairs):
        return "".join(f"<<<P {i}>>>\n{t}\n" for i, t in pairs)

    A = ("Вертикальная ось показывает смертность от рака на сто тысяч человек, "
         "а горизонтальная — годы с двухтысячного по двадцатый.")
    B = ("У мужчин первое место занимает рак предстательной железы, за ним "
         "идут рак лёгкого и рак ободочной кишки.")
    src = {"s26.b0031": "The vertical plot shows cancer mortality rates.",
           "s26.b0032": "For men, prostate cancer leads with 299,010 cases."}
    ids = ["s26.b0031", "s26.b0032"]
    try:
        P._parse_translate(answer((ids[0], B), (ids[1], B)), ids, src)
        ok("повтор перевода у соседей — переспросить", False, "разбор промолчал")
    except ValueError as e:
        ok("повтор перевода у соседей — переспросить", "s26.b0031" in str(e), e)

    got, _ = P._parse_translate(answer((ids[0], A), (ids[1], B)), ids, src)
    ok("разные переводы проходят", got[ids[0]] == A and got[ids[1]] == B, got)

    # Повтор законен там, где повторяется сам оригинал: строка припева,
    # одинаковая подпись под двумя рисунками.
    same = {i: "See figure for details on the trial outcome." for i in ids}
    got, _ = P._parse_translate(answer((ids[0], A), (ids[1], A)), ids, same)
    ok("одинаковый оригинал — повтор законен", got[ids[1]] == A, got)

    # Короткие блоки не сравниваем: «Рис. 3.1» и «Рис. 3.2» близки всегда.
    short = {"s01.b0001": "Figure 3.1", "s01.b0002": "Figure 3.2"}
    sids = list(short)
    got, _ = P._parse_translate(answer((sids[0], "Рис. 3.1"), (sids[1], "Рис. 3.1")),
                                sids, short)
    ok("короткие строки не сравниваем", len(got) == 2, got)

    print(f"\nслучаев: {len(TAILS) + 6}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
