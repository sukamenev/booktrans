# -*- coding: utf-8 -*-
"""Служебные указатели сносок [^N]: якорение при сборке и страж целостности.

Переводчик ставит указатель за поясняемым словом; правка, потерявшая или
добавившая указатель, отвергается; сборка ставит знак по указателю, лишние
указатели вычищает, а в переводах без указателей ищет термин, как раньше.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from booktrans import output, pipeline as P  # noqa: E402


def main():
    bad = cases = 0

    def ok(name, cond, got=""):
        nonlocal bad, cases
        cases += 1
        if not cond:
            bad += 1
            print(f"  РАСХОЖДЕНИЕ: {name} {got}")

    tok = output.NOTE_AT.format("b1")

    # знак встаёт по указателю, прижимаясь к слову
    t = output.anchor_note("Члены Протектората [^1] собрались.", "b1", ["Иное"])
    ok("знак по указателю", t == f"Члены Протектората{tok} собрались.", t)

    # первый указатель принимает знак, остальные вычищаются
    t = output.anchor_note("Раз [^1] и два [^2].", "b1", None)
    ok("лишний указатель вычищен", t == f"Раз{tok} и два.", t)

    # без указателя работает старый поиск термина
    t = output.anchor_note("Члены Протектората собрались.", "b1", ["Протекторат"])
    ok("поиск термина жив", tok in t and t.index(tok) == len("Члены Протектората"), t)

    # блок без сноски: указатели вычищаются подчистую
    t = output.strip_note_marks("Слово [^3] и ещё [^12].")
    ok("вычистка без сноски", t == "Слово и ещё.", t)

    # страж: правка потеряла указатель — различие видно
    ok("потеря указателя ловится",
       P._marks_differ("Слово [^1] тут.", "Слово тут."))
    ok("перенос указателя не ловится",
       not P._marks_differ("Слово [^1] тут.", "Тут [^1] слово."))
    ok("самовольный указатель ловится",
       P._marks_differ("Слово тут.", "Слово [^1] тут."))

    # страж сверки: исправление без указателя отвергается с причиной
    out = ("[[[VERDICT b1 translation]]]\nцитата — суть\n"
           "[[[P b1]]]\nСлово тут.\n[[[/P b1]]]")
    try:
        P._parse_verify(out, {"b1"}, must=["b1"], snap={"b1": "Слово [^1] тут."})
        ok("сверка: указатель потерян — отвергнуто", False)
    except ValueError as e:
        ok("сверка: указатель потерян — отвергнуто", "указатели сносок" in str(e), e)

    # страж сверки: указатель сохранён — исправление проходит
    out = ("[[[VERDICT b1 translation]]]\nцитата — суть\n"
           "[[[P b1]]]\nТут [^1] слово.\n[[[/P b1]]]")
    _, _, fixes = P._parse_verify(out, {"b1"}, must=["b1"],
                                  snap={"b1": "Слово [^1] тут."})
    ok("сверка: указатель сохранён — принято", fixes.get("b1") == "Тут [^1] слово.")

    print(f"  notemark_check          случаев: {cases}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
