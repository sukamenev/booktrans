#!/usr/bin/env python3
"""Проверка ссылок, вытащенных из pdf.

`pdftotext` отдаёт голый текст, и ссылки пропадают целиком: указатель
перестаёт быть указателем, doi в примечании становится строкой. Тот же poppler
умеет отдать разметку, и ссылки берутся оттуда — вторым чтением, ради одних
адресов.

Ошибиться тут можно тихо в обе стороны: поставить ярлык не туда — испортить
текст, который потом пойдёт в перевод; не поставить — потерять ссылку молча.
Поэтому проверяется и разбор разметки, и раскладка ярлыков по блокам.

    python3 tests/pdflinks_check.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from booktrans import build as B, extract as E           # noqa: E402

BOOK = "book.html"


def xml(*pages):
    """Разметка pdftohtml: страница — список строк с готовыми <text>."""
    body = "".join(f'<page number="{n}">{"".join(rows)}</page>'
                   for n, rows in pages)
    return f'<?xml version="1.0" encoding="UTF-8"?><pdf2xml>{body}</pdf2xml>'


def row(*parts):
    return "<text>" + "".join(parts) + "</text>"


def a(text, to):
    return f'<a href="{BOOK}#{to}">{text}</a>' if isinstance(to, int) \
        else f'<a href="{to}">{text}</a>'


def blocks(*rows):
    """(номер страницы, текст) → блоки, как их строит чтение pdf."""
    return [{"id": f"s01.b{i:04d}", "kind": "p", "text": t, "_page": p}
            for i, (p, t) in enumerate(rows, 1)]


def main():
    bad = 0

    def ok(name, cond, got=""):
        nonlocal bad
        print(f"  {name:52} {'совпадает' if cond else 'РАСХОЖДЕНИЕ'}"
              + ("" if cond else f"   вышло: {got}"))
        bad += not cond

    # --- разбор разметки

    # Ссылка приходит кусками: «98–100» и запятая за ней — разные строчки
    # разметки с одним адресом. Их надо склеить.
    got = E._links_from_xml(xml((7, [row(a("98–100", 111), a(",", 111)),
                                     row(a("190", 203))])))
    ok("соседние куски одной ссылки склеиваются",
       got == {7: [("98–100", 111), ("190", 203)]}, got)

    # А несоседние — нет: на странице описаний картинок один и тот же адрес
    # стоит и в начале абзаца, и в конце («Description 2:» … «BACK»).
    got = E._links_from_xml(xml((9, [row(a("Description 2:", 20)),
                                     row("много текста между ними"),
                                     row(a("BACK", 20))])))
    ok("далёкие куски с одним адресом не склеиваются",
       got == {9: [("Description 2", 20), ("BACK", 20)]}, got)

    got = E._links_from_xml(xml((3, [row(a("doi.org/10.1/x", "https://doi.org/10.1/x"))])))
    ok("внешний адрес берётся как есть",
       got == {3: [("doi.org/10.1/x", "https://doi.org/10.1/x")]}, got)

    # Якорь в один знак — мусор вёрстки: у живой книги так пришли «I» и «.»,
    # обе на одну страницу. Цифра — не мусор: в указателе это номер страницы.
    got = E._links_from_xml(xml((4, [row(a("I", 19)), row(a(".", 19)), row(a("5", 12))])))
    ok("одиночная буква отброшена, цифра оставлена",
       got == {4: [("5", 12)]}, got)

    ok("мусор вместо разметки не валит чтение", E._links_from_xml("не xml") == {})

    # --- раскладка по блокам

    bs = blocks((1, "Начало книги."), (7, "abatacept, 225 Abbott, 85"),
                (12, "Цель ссылки."))
    n = E._put_links(bs, {7: [("225", 12), ("85", 1)]})
    ok("ярлыки встали по порядку", n == 2
       and bs[1]["text"] == "abatacept, <a1>225</a1> Abbott, <a2>85</a2>",
       bs[1]["text"])
    ok("адреса указывают на блоки", bs[1]["links"] == ["#s01.b0003", "#s01.b0001"],
       bs[1].get("links"))

    # Лигатура: у «fig. 2.1» связка «fi» — отдельный знак вёрстки, и в разметке
    # она остаётся снаружи ссылки. Ярлык должен охватить слово целиком.
    bs = blocks((1, "Цель."), (7, "видно на fig. 2.1 в главе"))
    E._put_links(bs, {7: [("g. 2.1", 1)]})
    ok("якорь без лигатуры дотягивается до начала слова",
       bs[1]["text"] == "видно на <a1>fig. 2.1</a1> в главе", bs[1]["text"])

    # Совпадение посреди слова — не якорь: так «I» попадала внутрь «Illderly».
    bs = blocks((1, "Цель."), (7, "назовём их Illderly, и вот почему"))
    E._put_links(bs, {7: [("I", 1)]})
    ok("совпадение внутри слова не берётся", "links" not in bs[1], bs[1])

    # Ссылка целится страницей, а не абзацем; страница своя же — ссылки нет.
    bs = blocks((7, "Здесь и цель, и ссылка на неё."), (8, "Дальше."))
    E._put_links(bs, {7: [("цель", 7)]})
    ok("ссылка на самого себя не ставится", "links" not in bs[0], bs[0])

    # Блок начался на одной странице, а якорь пришёл со следующей.
    bs = blocks((1, "Цель."), (7, "начало абзаца и конец его со ссылкой 225 тут"))
    E._put_links(bs, {8: [("225", 1)]})
    ok("якорь со следующей страницы находит свой блок",
       bs[1]["text"].count("<a1>") == 1, bs[1]["text"])

    # Не нашли — молча мимо, и следующий якорь всё равно ставится.
    bs = blocks((1, "Цель."), (7, "тут есть 225, а вот 999 нет"))
    E._put_links(bs, {7: [("777", 1), ("999", 1)]})
    ok("ненайденный якорь не срывает остальные",
       bs[1]["text"] == "тут есть 225, а вот <a1>999</a1> нет", bs[1]["text"])

    # Блок, перебираемый дважды (он начался на прошлой странице), уже несёт
    # ярлыки, и число из указателя совпадало с цифрами внутри `<a28>`.
    bs = blocks((1, "Цель."), (7, "abatacept, 28 Abbott, 85"))
    E._put_links(bs, {7: [("28", 1)], 8: [("85", 1)]})
    ok("якорь не лезет внутрь поставленного ярлыка",
       bs[1]["text"] == "abatacept, <a1>28</a1> Abbott, <a2>85</a2>", bs[1]["text"])

    # Цель на странице без текста — берём ближайшую следующую, а не пустоту.
    bs = blocks((1, "Начало."), (7, "смотри 300"), (14, "Цель."))
    E._put_links(bs, {7: [("300", 12)]})
    ok("цель на пустой странице съезжает на ближайшую",
       bs[1].get("links") == ["#s01.b0003"], bs[1].get("links"))

    # --- перенос ярлыков на готовый перевод
    #
    # Ярлык ставится в оригинал, и модель переносит его сама — но у книги,
    # переведённой раньше, чем ссылки научились читаться, перевода с ярлыком
    # нет, а ссылка есть. Возвращаем их без обращения к модели.
    RE = [
        # Якорь переведён, но номер уцелел: он и есть примета.
        ("номер якоря в переводе",
         "Figure 1.1. The five dimensions <a1>Description 1</a1>",
         "Рис. 1.1. Пять измерений. Описание 1", ["#s26.b0001"],
         "Рис. 1.1. Пять измерений. <a1>Описание 1</a1>"),
        ("слово перед номером захватывается",
         "shown in <a1>figure 3.2</a1> below",
         "показана на рисунке 3.2 ниже", ["#s06.b0031"],
         "показана на <a1>рисунке 3.2</a1> ниже"),
        # Адрес перевод переживает дословно — его и ищем целиком.
        ("адрес найден дословно",
         "see <a1>https://doi.org/10.1/x</a1> for more",
         "см. https://doi.org/10.1/x подробнее", ["https://doi.org/10.1/x"],
         "см. <a1>https://doi.org/10.1/x</a1> подробнее"),
        # Число в переводе не одно — гадать не станем.
        ("неоднозначный номер пропускается",
         "as <a1>figure 7</a1> shows", "как видно на 7 и 7 рисунках", ["#s10.b0008"],
         "как видно на 7 и 7 рисунках"),
        # В переводе ярлыки уже есть — значит модель переводила с ними.
        ("готовую разметку не трогаем",
         "see <a1>figure 3.2</a1>", "см. <a1>рисунок 3.2</a1>", ["#s06.b0031"],
         "см. <a1>рисунок 3.2</a1>"),
        ("без ссылок ничего не делаем", "текст", "текст", [], "текст"),
    ]
    for name, src, tr, links, want in RE:
        got = B.relink(src, tr, links)
        ok(f"перенос: {name}", got == want, got)

    print(f"\nслучаев: {13 + len(RE)}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
