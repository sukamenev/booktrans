#!/usr/bin/env python3
"""Проверка склейки абзацев, разорванных концом страницы.

Из pdf абзац приходит разрезанным пополам: конец страницы обрывает его на
переносе («слу-» / «шал») или просто посреди фразы («подцепил компас» /
«стрелку»). Метка `+` для этого и есть, но модель ставит её не всегда, и
переводчик получает по половине предложения.

Правило машинное и работает без модели, поэтому и проверяется без неё. Здесь
записано и то, что обязано склеиваться, и то, что трогать нельзя: лишняя
склейка сводит два абзаца в один так же тихо, как лишний разрыв их рвёт.

    python3 tests/glue_check.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from booktrans import extract as E                       # noqa: E402
from booktrans import format as F                        # noqa: E402

# (имя, куски, пометки модели, что должно выйти).
CASES = [
    ("перенос по слогам",
     ["Ночью я лежал в постели и слу-", "шал крик матери."], {},
     [("p", "Ночью я лежал в постели и слушал крик матери.")]),

    ("перенос, а дальше прописная",
     ["дал ему пропуск в клуб. Он об-", "Как следствие, отец вмешался."], {},
     [("p", "дал ему пропуск в клуб. Он об-"),
      ("p", "Как следствие, отец вмешался.")]),

    ("обрыв без знака",
     ["Я спустился в подвал и подцепил компас", "стрелку к трансформатору."], {},
     [("p", "Я спустился в подвал и подцепил компас стрелку к трансформатору.")]),

    ("обрыв на запятой",
     ["Приехали друзья, родные,", "соседи и все остальные."], {},
     [("p", "Приехали друзья, родные, соседи и все остальные.")]),

    ("точка в конце — новый абзац",
     ["Он ушёл и больше не вернулся.", "год спустя его нашли."], {},
     [("p", "Он ушёл и больше не вернулся."), ("p", "год спустя его нашли.")]),

    ("следующий с прописной — новый абзац",
     ["Он ушёл и больше не вернулся", "Год спустя его нашли."], {},
     [("p", "Он ушёл и больше не вернулся"), ("p", "Год спустя его нашли.")]),

    # Стих кончается без точки, а следующая строка идёт со строчной — по
    # признакам это ровно тот же обрыв. Спасает пометка: склейка добирается
    # только до прозы.
    ("стихи не склеиваются",
     ["в полях под снегом и дождём", "мой милый друг"], {1: "verse", 2: "verse"},
     [("verse", "в полях под снегом и дождём"), ("verse", "мой милый друг")]),

    ("к заголовку не клеим",
     ["Глава первая", "рассказывает о детстве."], {1: "title"},
     [("title", "Глава первая"), ("p", "рассказывает о детстве.")]),

    ("листинг не склеивается",
     ["x = 1", "y = x + 2"], {1: "code", 2: "code"},
     [("code", "x = 1"), ("code", "y = x + 2")]),

    ("пометка модели сильнее: skip выбрасывает",
     ["Он лежал в постели и слу-", "THE SCIENTIST", "шал крик."], {2: "skip"},
     [("p", "Он лежал в постели и слушал крик.")]),
]

# Та же беда с другой стороны: `skip` и `toc` выбрасывают кусок насовсем, и
# модель метит ими не только колонтитулы с оглавлением. Что вернуть, а что
# оставить выброшенным — (имя, куски, пометки, какие номера обязаны вернуться).
UNDO = [
    ("короткий обрывок за незакрытой фразой",
     ["о чём мало говорят в медицинской", "профессии."], {2: "skip"}, [2]),
    ("после закрытой фразы не возвращаем",
     ["Он ушёл и больше не вернулся.", "выходные данные"], {2: "skip"}, []),
    ("с прописной не возвращаем",
     ["строка без знака в конце", "THE SCIENTIST"], {2: "skip"}, []),
    # Выброшенный кусок не считается предыдущим: за колонтитулом идёт не
    # продолжение фразы, а следующий колонтитул.
    ("за выброшенным куском не возвращаем",
     ["Конец главы.", "www.example.com", "@example"], {2: "skip", 3: "skip"}, []),
    ("длинный абзац возвращаем и после точки",
     ["Он ушёл и больше не вернулся.", "А" * 200], {2: "skip"}, [2]),

    # Указатель устроен как оглавление — имя, провал, номер страницы, — и
    # модель метит его `toc`. Отличает их место: оглавление стоит перед тем,
    # что перечисляет, а указатель — под своим заголовком в задней части.
    ("указатель под своим заголовком возвращаем",
     ["Index", "aspirin, 145", "atherosclerosis, 11 , 109"],
     {1: "title", 2: "toc", 3: "toc"}, [2, 3]),
    ("оглавление в начале выбрасываем",
     ["Contents", "Глава первая . . . 7", "Глава вторая . . . 34"],
     {1: "title", 2: "toc", 3: "toc"}, []),
    # Оглавление бывает и в конце книги — так набирают во Франции и в Японии.
    # Правило смотрит на заголовок, а не на место, поэтому такое оглавление
    # выбрасывается наравне с передним: «Оглавление» не заголовок задней части.
    ("оглавление в конце выбрасываем тоже",
     ["Указатель", "аспирин, 145", "Оглавление", "Глава первая . . . 7",
      "Глава вторая . . . 34"],
     {1: "title", 2: "toc", 3: "title", 4: "toc", 5: "toc"}, [2]),
    ("без заголовка вовсе не возвращаем",
     ["аспирин, 145", "атеросклероз, 11"], {1: "toc", 2: "toc"}, []),
]


def main():
    bad = 0
    for name, paras, marks, want in CASES:
        got = [(k, t) for k, t, _ in F.apply(paras, marks)]
        ok = got == want
        print(f"  {name:34} {'совпадает' if ok else 'РАСХОЖДЕНИЕ'}")
        if not ok:
            print(f"      ждали: {want}")
            print(f"      вышло: {got}")
        bad += not ok
    for name, paras, marks, want in UNDO:
        marks = dict(marks)
        E._undo_drop(paras, marks)
        got = sorted(i for i, m in marks.items() if m == "p")
        ok = got == want
        print(f"  {name:34} {'совпадает' if ok else 'РАСХОЖДЕНИЕ'}")
        if not ok:
            print(f"      ждали вернуть: {want}   вышло: {got}")
        bad += not ok
    print(f"\nслучаев: {len(CASES) + len(UNDO)}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
