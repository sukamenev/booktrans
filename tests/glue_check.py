#!/usr/bin/env python3
"""Проверка склейки абзацев, разорванных концом страницы.

Из pdf абзац приходит разрезанным пополам: конец страницы обрывает его на
переносе («слу-» / «шал») или просто посреди фразы («подцепил компас» /
«стрелку»). Метка `+` для этого и есть, но модель ставит её не всегда, и
переводчик получает по половине предложения.

Правило машинное и работает без модели, поэтому и проверяется без неё. Здесь
записано и то, что обязано склеиваться, и то, что трогать нельзя: лишняя
склейка сводит два абзаца в один так же тихо, как лишний разрыв их рвёт.

    python3 tests/glue_check.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from booktrans import format as F                        # noqa: E402

# (имя, куски, пометки модели, что должно выйти).
CASES = [
    ("перенос по слогам",
     ["Ночью я лежал в постели и слу-", "шал крик матери."], {},
     [("p", "Ночью я лежал в постели и слушал крик матери.")]),

    ("перенос, а дальше прописная",
     ["дал ему пропуск в клуб. Он об-", "Как следствие, отец вмешался."], {},
     [("p", "дал ему пропуск в клуб. Он об-"),
      ("p", "Как следствие, отец вмешался.")]),

    ("обрыв без знака",
     ["Я спустился в подвал и подцепил компас", "стрелку к трансформатору."], {},
     [("p", "Я спустился в подвал и подцепил компас стрелку к трансформатору.")]),

    ("обрыв на запятой",
     ["Приехали друзья, родные,", "соседи и все остальные."], {},
     [("p", "Приехали друзья, родные, соседи и все остальные.")]),

    ("точка в конце — новый абзац",
     ["Он ушёл и больше не вернулся.", "год спустя его нашли."], {},
     [("p", "Он ушёл и больше не вернулся."), ("p", "год спустя его нашли.")]),

    ("следующий с прописной — новый абзац",
     ["Он ушёл и больше не вернулся", "Год спустя его нашли."], {},
     [("p", "Он ушёл и больше не вернулся"), ("p", "Год спустя его нашли.")]),

    # Стих кончается без точки, а следующая строка идёт со строчной — по
    # признакам это ровно тот же обрыв. Спасает пометка: склейка добирается
    # только до прозы.
    ("стихи не склеиваются",
     ["в полях под снегом и дождём", "мой милый друг"], {1: "verse", 2: "verse"},
     [("verse", "в полях под снегом и дождём"), ("verse", "мой милый друг")]),

    ("к заголовку не клеим",
     ["Глава первая", "рассказывает о детстве."], {1: "title"},
     [("title", "Глава первая"), ("p", "рассказывает о детстве.")]),

    ("листинг не склеивается",
     ["x = 1", "y = x + 2"], {1: "code", 2: "code"},
     [("code", "x = 1"), ("code", "y = x + 2")]),

    ("пометка модели сильнее: skip выбрасывает",
     ["Он лежал в постели и слу-", "THE SCIENTIST", "шал крик."], {2: "skip"},
     [("p", "Он лежал в постели и слушал крик.")]),
]


def main():
    bad = 0
    for name, paras, marks, want in CASES:
        got = [(k, t) for k, t, _ in F.apply(paras, marks)]
        ok = got == want
        print(f"  {name:34} {'совпадает' if ok else 'РАСХОЖДЕНИЕ'}")
        if not ok:
            print(f"      ждали: {want}")
            print(f"      вышло: {got}")
        bad += not ok
    print(f"\nслучаев: {len(CASES)}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
