#!/usr/bin/env python3
"""Проверка опознания списка литературы.

Библиографию в переводе оставляют как есть, и блоки с ней помечаются `asis`:
они не идут ни в перевод, ни в редактуру, ни в проверки. Ошибка тут тиха с
обеих сторон — не опознали, и три сотни блоков переводятся впустую; опознали
лишнее, и глава останется на языке оригинала.

Раньше признаком были три года издания и три номера записи в одном блоке:
из pdf библиография приходила страницей целиком. Когда абзацы стали
разбираться по-настоящему, запись заняла свой блок, и правило замолчало —
на живой книге из 329 блоков списка `asis` получил ровно один. Теперь список
ищется рядом блоков: номера записей идут вверх, 1, 2, 3…

    python3 tests/refs_check.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from booktrans import extract as E                       # noqa: E402

PROSE = ("Он спустился в подвал и подцепил стрелку компаса к трансформатору, "
         "а потом смотрел, как она вертится.")


def refs(n, first=1, year=True, cont=True):
    """Список литературы: на запись строка, иногда с продолжением."""
    out = []
    for i in range(first, first + n):
        y = f" {1940 + i}." if year else ""
        out.append(f'{i}. Лилли, Джон К.{y} «Работа номер {i} о дельфинах и людях»')
        if cont:
            out.append(f"Известия института, том {i}, с. {i * 7}-{i * 7 + 12}")
    return out


def blocks(texts, kind="p"):
    return [{"id": f"s01.b{i:04d}", "kind": kind, "text": t}
            for i, t in enumerate(texts, 1)]


def cites(n, first=1):
    """Концевые сноски-ссылки: лемма, двоеточие, источник."""
    return [f'"a phrase number {i}": Hans Moravec, Mind Children: The Future '
            f'of Robot Intelligence (Harvard University Press, {1980 + i}), {i * 7}.'
            for i in range(first, first + n)]


# Содержательное примечание: авторский текст, его переводить обязательно.
# Второе — с двоеточием и годом нарочно: по одному признаку оно сошло бы за
# ссылку.
TALK = ["The actual quote, found chalked on a blackboard after his death, reads "
        "otherwise, and the difference matters here.",
        "Levin has gotten some experimental support: He has successfully "
        "reprogrammed cells, and others have repeated it since."]


def marked(bs):
    for b in bs:
        b.pop("asis", None)
    E._mark_refs(bs)
    E._mark_cites(bs)
    return [b["text"] for b in bs if b.get("asis")]


# (имя, блоки, сколько блоков обязано стать asis).
#
# Счёт всюду на единицу меньше, чем строк в списке: продолжение последней
# записи с прописной буквы не захватывается. Дочитывать хвост наугад дороже,
# чем оставить одну строку переведённой: лишний блок `asis` — это кусок
# книги, молча оставшийся на языке оригинала.
CASES = [
    ("список построчно", blocks([PROSE] + refs(8) + [PROSE]), 15),

    # Порванная цифра — обычное дело в распознанном тексте: ряд рвётся, но
    # между двумя его кусками ничего кроме списка быть не может.
    ("список с битым номером",
     blocks([PROSE] + refs(4) + ["З. Лилли, Джон К. 1955. «Работа о китах»"]
            + refs(4, first=6) + [PROSE]), 16),

    ("перечисление внутри абзаца",
     blocks([PROSE,
             "Опыт делится на этапы: (1) Первые полчаса. (2) Потом легчает. "
             "(3) К часу приходит покой. (4) Дальше начинается главное. "
             "(5) К концу второго часа всё стихает.", PROSE]), 0),

    ("проза с годами", blocks(
        [PROSE, "В 1938 году он поступил, в 1942 окончил, а в 1953 ушёл на "
                "государственную службу и пробыл там до 1958 года.", PROSE]), 0),

    ("нумерованный список без годов",
     blocks([PROSE] + refs(8, year=False, cont=False) + [PROSE]), 0),

    ("список из одной записи", blocks([PROSE] + refs(1) + [PROSE]), 0),

    # Старое правило: библиография пришла страницей в одном блоке.
    ("список одним блоком", blocks(
        [PROSE, "1. Лилли, Дж. 1941. «Первая». 2. Лилли, Дж. 1942. «Вторая». "
                "3. Лилли, Дж. 1943. «Третья».", PROSE]), 1),

    ("заголовок списка цепляется", blocks(
        [PROSE, "Библиография"] + refs(8) + [PROSE]), 16),

    # Концевые сноски. Помечается каждая подходящая внутри ряда, а не вся
    # область: содержательные примечания стоят вперемешку со ссылками.
    ("ряд концевых ссылок", blocks(cites(8), kind="note"), 8),

    ("примечание внутри ряда остаётся",
     blocks(cites(4) + TALK[:1] + cites(4, first=5), kind="note"), 8),

    ("одиночная ссылка среди примечаний",
     blocks(TALK * 3 + cites(1) + TALK * 3, kind="note"), 0),

    ("содержательные примечания", blocks(TALK * 4, kind="note"), 0),

    # Тот же ряд, но абзацами: вид `note` ставит epub, а в pdf раздел
    # примечаний приходит простым текстом, и ставить его некому. Пока правило
    # смотрело на вид, из 1561 блока такого списка не опозналось ни одного.
    ("ряд ссылок абзацами", blocks(cites(8)), 8),

    # Внутри ряда помечается всё подряд: запись занимает несколько блоков, и
    # хвост выходных данных сам на ссылку не похож.
    ("обрывок записи внутри ряда",
     blocks(cites(4) + ["Известия института, том 9, с. 63-75."] + cites(4, first=5)),
     9),

    # А вот наружу ряд не растёт: проза за последней записью остаётся прозой.
    ("проза после ряда не цепляется", blocks(cites(8) + [PROSE] * 3), 8),

    ("одиночная ссылка среди прозы", blocks([PROSE] * 3 + cites(1) + [PROSE] * 3), 0),
]


def main():
    bad = 0
    for name, bs, want in CASES:
        got = marked(bs)
        ok = len(got) == want
        print(f"  {name:30} {'совпадает' if ok else 'РАСХОЖДЕНИЕ'}")
        if not ok:
            print(f"      ждали блоков asis: {want}, вышло: {len(got)}")
            for t in got[:4]:
                print(f"         {t[:70]!r}")
        # Прозу не помечаем никогда: это проверяется отдельно от счёта.
        if PROSE in got:
            print("      ЗАХВАЧЕНА ПРОЗА")
            ok = False
        bad += not ok
    print(f"\nслучаев: {len(CASES)}   с расхождениями: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
